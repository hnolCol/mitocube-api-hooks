import { useQuery, useMutation } from "@tanstack/react-query"

export function createPolicyAPI(client) {

    /** @description Endpoint: GET '/api/policy' */
    async function getPolicies_API() {
        const res = await client.get(`/policy`)
        return res.data
    }

    const useGetPolicies = (APIParams = {}, useQueryOptions = {}) => {
        return useQuery({
            queryKey: ["getPolicies"],
            queryFn: () => getPolicies_API(),
            ...useQueryOptions
        })
    }

    /** @description Endpoint: GET '/api/policy/permissions' - what the current user may do (insert, edit, delete) */
    async function getPolicyPermissions_API() {
        const res = await client.get(`/policy/permissions`)
        return res.data
    }

    const useGetPolicyPermissions = (APIParams = {}, useQueryOptions = {}) => {
        return useQuery({
            queryKey: ["getPolicyPermissions"],
            queryFn: () => getPolicyPermissions_API(),
            ...useQueryOptions
        })
    }

    /** @description Endpoint: GET '/api/policy/status' - one entry per existing policy */
    async function getPolicyStatus_API() {
        const res = await client.get(`/policy/status`)
        return res.data
    }

    const useGetPolicyStatus = (APIParams = {}, useQueryOptions = {}) => {
        return useQuery({
            queryKey: ["getPolicyStatus"],
            queryFn: () => getPolicyStatus_API(),
            ...useQueryOptions
        })
    }

    /** @description Endpoint: POST '/api/policy/{tag}/agree' */
    async function agreePolicy_API({ tag }) {
        const res = await client.post(`/policy/${tag}/agree`)
        return res.data
    }

    const useAgreePolicy = (useMutationOptions = {}) => {
        return useMutation({
            mutationFn: (APIParams) => agreePolicy_API({ ...APIParams }),
            ...useMutationOptions
        })
    }

    /**
     * @description Endpoint: POST '/api/policy' - the tag is generated by the backend from the title
     * @param {Object} props
     * @param {String} props.title
     * @param {String} props.text - markdown
     * @param {Boolean} props.required
     */
    async function createPolicy_API({ type, title, text, required }) {
        const res = await client.post(`/policy`, { type, title, text, required })
        return res.data
    }

    const useCreatePolicy = (useMutationOptions = {}) => {
        return useMutation({
            mutationFn: (APIParams) => createPolicy_API({ ...APIParams }),
            ...useMutationOptions
        })
    }

    /**
     * @description Endpoint: PUT '/api/policy/{tag}'
     * @param {Object} props
     * @param {String} props.tag
     * @param {String} props.title
     * @param {String} props.text - markdown
     * @param {Boolean} props.required
     * @param {Boolean} props.bump_version - all users must agree again
     */
    async function updatePolicy_API({ tag, title, text, required, bump_version }) {
        const res = await client.put(`/policy/${tag}`, { title, text, required, bump_version })
        return res.data
    }

    const useUpdatePolicy = (useMutationOptions = {}) => {
        return useMutation({
            mutationFn: (APIParams) => updatePolicy_API({ ...APIParams }),
            ...useMutationOptions
        })
    }

    /** @description Endpoint: DELETE '/api/policy/{tag}' */
    async function deletePolicy_API({ tag }) {
        const res = await client.delete(`/policy/${tag}`)
        return res.data
    }

    const useDeletePolicy = (useMutationOptions = {}) => {
        return useMutation({
            mutationFn: (APIParams) => deletePolicy_API({ ...APIParams }),
            ...useMutationOptions
        })
    }

    return {
        useGetPolicies,
        useGetPolicyPermissions,
        useGetPolicyStatus,
        useAgreePolicy,
        useCreatePolicy,
        useUpdatePolicy,
        useDeletePolicy
    }
}